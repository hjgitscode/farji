import { AbiCoder, keccak256, TypedDataEncoder } from "ethers";
import type { CanonicalContent } from "./canonical";
import { CONTENT_TYPES, CREDENTIAL_ID_TAG, SUBJECT_TAG } from "./constants";
import { isBytes32 } from "./encoding";

// Identifier and commitment formulas (BLOCKCHAIN_MODEL §4, MERKLE_MODEL §1). Pure.
//
//   credentialId      = keccak256(abi.encode(bytes32 CREDENTIAL_ID_TAG, bytes32 orgId, bytes32 credentialSalt))
//   subjectCommitment = keccak256(abi.encode(bytes32 SUBJECT_TAG, bytes16 platformSubjectId, bytes32 subjectSalt))
//   contentDigest     = hashStruct("CredentialContent", canonicalContent ∪ { contentSalt })
//
// Salts are random 32-byte values generated by the caller (server/issuance/random.ts); this
// module never generates randomness.

const abi = AbiCoder.defaultAbiCoder();

const need32 = (name: string, v: string) => {
  if (!isBytes32(v)) throw new Error(`${name} must be a lowercase 0x bytes32`);
};

export function credentialIdOf(orgId: string, credentialSalt: string): string {
  need32("orgId", orgId);
  need32("credentialSalt", credentialSalt);
  return keccak256(abi.encode(["bytes32", "bytes32", "bytes32"], [CREDENTIAL_ID_TAG, orgId, credentialSalt]));
}

/** `platformSubjectId` is the 16 raw bytes of the candidate's internal user UUID (`uuidToBytes16`). */
export function subjectCommitmentOf(platformSubjectId: string, subjectSalt: string): string {
  if (!/^0x[0-9a-f]{32}$/.test(platformSubjectId)) throw new Error("platformSubjectId must be a lowercase 0x bytes16");
  need32("subjectSalt", subjectSalt);
  return keccak256(abi.encode(["bytes32", "bytes16", "bytes32"], [SUBJECT_TAG, platformSubjectId, subjectSalt]));
}

/** The salted `CredentialContent` struct value that is hashed and shown in the wallet prompt. */
export function saltedContent(content: CanonicalContent, contentSalt: string): CanonicalContent & { contentSalt: string } {
  need32("contentSalt", contentSalt);
  return { ...content, contentSalt };
}

export function contentDigestOf(content: CanonicalContent, contentSalt: string): string {
  return TypedDataEncoder.hashStruct("CredentialContent", CONTENT_TYPES, saltedContent(content, contentSalt));
}

/** The three salts must be pairwise distinct (also a database CHECK). */
export function areDistinctSalts(credentialSalt: string, contentSalt: string, subjectSalt: string): boolean {
  return credentialSalt !== contentSalt && credentialSalt !== subjectSalt && contentSalt !== subjectSalt;
}
